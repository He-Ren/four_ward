"""Embed the Turing game's default config and question bank for file:// play."""

import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "src/turing/offline-data.js"


def content():
    config = json.loads((ROOT / "config/turing/default.json").read_text(encoding="utf-8"))
    scenarios = json.loads((ROOT / "assets/turing/scenarios.json").read_text(encoding="utf-8"))
    if type(config.get("k")) is not int or not 0 <= config["k"] <= 10:
        raise ValueError("k must be an integer from 0 to 10")
    if type(config.get("s")) not in (int, float) or not 0 <= config["s"] <= 60:
        raise ValueError("s must be a number from 0 to 60")
    if len(scenarios) < 10 or len({s["prompt"] for s in scenarios}) != len(scenarios):
        raise ValueError("At least 10 distinct questions are required")
    for scene in scenarios:
        if not isinstance(scene["prompt"], str) or not scene["prompt"].strip():
            raise ValueError("Question prompt is empty")
        for model in ("gpt", "deepseek", "doubao"):
            answer = scene.get("responses", {}).get(model)
            if not isinstance(answer, str) or not answer.strip():
                raise ValueError(f"Missing answer text for {model}")
    serialized = json.dumps({"config": config, "scenarios": scenarios}, ensure_ascii=False,
                            separators=(",", ":"), allow_nan=False)
    serialized = serialized.replace("\u2028", "\\u2028").replace("\u2029", "\\u2029")
    return ("// Generated by scripts/package_turing.py. Edit the original JSON files.\n"
            + "window.TuringData = " + serialized + ";\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check freshness without writing")
    args = parser.parse_args()
    generated = content()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != generated:
            sys.exit("Outdated Turing data; run python scripts/package_turing.py")
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(generated, encoding="utf-8", newline="\n")
    print(f'{"Checked" if args.check else "Generated"}: {OUTPUT.relative_to(ROOT)}')


if __name__ == "__main__":
    main()
