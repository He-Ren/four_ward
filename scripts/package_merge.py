"""Regenerate the double-click build using only Python's standard library.

The source modules intentionally use named imports/exports only. This small
packager supports that explicit subset; it is not a general JavaScript bundler.
Run with --check to detect stale generated files without writing anything.
"""
import argparse
import base64
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "src" / "merge"
MODULES = (
    "vendor", "config", "geometry", "assets", "physics",
    "renderer", "input", "audio", "main",
)
AUDIO_FILES = ("pop.mp3", "pop2.mp3", "drop-soft.wav")
AUDIO_MIME_TYPES = {".mp3": "audio/mpeg", ".wav": "audio/wav"}


def compile_module(name):
    source = (SOURCE / f"{name}.js").read_text(encoding="utf-8")
    exports = []

    def import_named(match):
        names, dependency = match.groups()
        if dependency not in MODULES[:MODULES.index(name)]:
            raise ValueError(f"Unordered dependency: {name} -> {dependency}")
        return f'const {{{names}}} = modules["{dependency}"];'

    def export_named(match):
        for part in match.group(1).split(","):
            if not part.strip():
                continue
            names = re.split(r"\s+as\s+", part.strip())
            exports.append(f"{names[-1]}: {names[0]}")
        return ""

    def export_declaration(match):
        kind, identifier = match.groups()
        exports.append(identifier)
        return f"{kind} {identifier}"

    source = re.sub(r'^import\s*\{([^}]+)\}\s*from\s*[\'"]\./([\w-]+)\.js[\'"];?', import_named, source, flags=re.M)
    source = re.sub(r'\bexport\s*\{([^}]+)\};?', export_named, source)
    source = re.sub(r'\bexport\s+(async\s+function|function|class|const|let)\s+(\w+)', export_declaration, source)
    if re.search(r"^(import|export)\s", source, flags=re.M):
        raise ValueError(f"Unsupported module syntax in {name}")
    return f'// ---- {name}.js ----\nmodules["{name}"] = (() => {{\n{source}\nreturn {{{", ".join(exports)}}};\n}})();\n'


def outputs():
    code = '// Generated by scripts/package_merge.py. Edit the source modules.\n(() => {\n"use strict";\nconst modules = Object.create(null);\n'
    code += "\n".join(compile_module(name) for name in MODULES)
    code += "})();\n"
    skin_path = ROOT / "config" / "merge" / "default.json"
    skin = json.loads(skin_path.read_text(encoding="utf-8"))
    images = {}
    for item in skin["items"]:
        image_path = (skin_path.parent / item["image"]).resolve()
        if not image_path.is_relative_to(ROOT) or image_path.suffix.lower() != ".png":
            raise ValueError("Offline defaults must use PNG files inside this repository")
        images[item["image"]] = "data:image/png;base64," + base64.b64encode(image_path.read_bytes()).decode("ascii")
    audio = {}
    for filename in AUDIO_FILES:
        audio_path = ROOT / "assets" / "merge" / filename
        mime = AUDIO_MIME_TYPES[audio_path.suffix]
        audio[f"./assets/merge/{filename}"] = f"data:{mime};base64," + base64.b64encode(audio_path.read_bytes()).decode("ascii")
    data = '// Generated from config/merge/default.json, its PNG files and merge audio clips.\nwindow.MergeOffline = '
    data += json.dumps({"skin": skin, "images": images, "audio": audio}, ensure_ascii=False, separators=(",", ":")) + ";\n"
    return {SOURCE / "game.js": code, SOURCE / "offline-data.js": data}


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify generated files without writing")
    check = parser.parse_args().check
    for path, content in outputs().items():
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                sys.exit(f"Outdated: {path.name}; run python scripts/package_merge.py")
        else:
            path.write_text(content, encoding="utf-8", newline="\n")
        print(f'{"Checked" if check else "Generated"}: {path.relative_to(ROOT)}')
